import os
import sqlite3
import webbrowser
import html
from datetime import datetime
from PyQt5.QtWidgets import QWidget, QVBoxLayout, QTableWidget, QTableWidgetItem, QPushButton, QMessageBox

from database.db_config import DB_PATH

# Optional: update to your actual logo path
CLINIC_LOGO_PATH = os.path.abspath("DrWs_Dental_Studio_Icon.ico")

CLINIC_NAME = "Dr. N's Dental Studio"
CLINIC_ADDRESS = "First Floor, Chovattukunnel Plaza, Erattupetta Road, Edappady, Pala, Bharananganam, Kerala 686578"
CLINIC_DOCTOR = "Neethu Mathew"


class AppointmentsReport(QWidget):
    def __init__(self, embed=False):
        super().__init__()
        layout = QVBoxLayout(self)

        self.table = QTableWidget()
        layout.addWidget(self.table)

        export_btn = QPushButton("Export HTML")
        export_btn.clicked.connect(self.export_html)
        layout.addWidget(export_btn)

        self.load_data()

    def showEvent(self, event):
        super().showEvent(event)
        self.load_data()  # Reload patients every time tab is shown

    def load_data(self):
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()

        cursor.execute("""
            SELECT a.appointment_id, p.name AS patient_name, a.doctor, a.date
            FROM appointments a
            LEFT JOIN patients p ON a.patient_id = p.patient_id
            ORDER BY a.date DESC
        """)
        rows = cursor.fetchall()
        conn.close()

        self.table.setColumnCount(4)
        self.table.setHorizontalHeaderLabels(["ID", "Patient Name", "Doctor", "Date"])
        self.table.setRowCount(len(rows))

        for r, row in enumerate(rows):
            for c, col in enumerate(row):
                self.table.setItem(r, c, QTableWidgetItem(str(col)))

    def export_html(self):
        reports_dir = os.path.join(os.getcwd(), "Reports")
        os.makedirs(reports_dir, exist_ok=True)

        date_str = datetime.now().strftime("%Y-%m-%d_%H%M%S")
        filename = os.path.join(reports_dir, f"appointments_report_{date_str}.html")

        # Fetch fresh data
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        cursor.execute("""
            SELECT a.appointment_id, p.name AS patient_name, a.doctor, a.date
            FROM appointments a
            LEFT JOIN patients p ON a.patient_id = p.patient_id
            ORDER BY a.date DESC
        """)
        rows = cursor.fetchall()
        conn.close()

        def esc(s):
            return html.escape(str(s))

        html_rows = ""
        for r in rows:
            html_rows += "<tr>"
            html_rows += f"<td>{esc(r[0])}</td>"
            html_rows += f"<td>{esc(r[1])}</td>"
            html_rows += f"<td>{esc(r[2])}</td>"
            html_rows += f"<td>{esc(r[3])}</td>"
            html_rows += "</tr>\n"

        logo_tag = ""
        if os.path.exists(CLINIC_LOGO_PATH):
            logo_tag = f'<img src="file://{CLINIC_LOGO_PATH}" alt="Clinic Logo" style="height:80px;">'

        html_content = f"""<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>Appointments Report - {esc(date_str)}</title>
<style>
    body {{ font-family: Arial, Helvetica, sans-serif; margin: 24px; }}
    .header {{ display:flex; align-items:center; gap:16px; }}
    .clinic-info {{ line-height:1.1; }}
    h1 {{ margin:0; font-size:20px; }}
    .meta {{ margin-top:6px; color:#333; font-size:13px; }}
    table {{ width:100%; border-collapse:collapse; margin-top:16px; }}
    th, td {{ border:1px solid #ddd; padding:8px; }}
    th {{ background:#f2f2f2; }}
    .footer {{ margin-top:18px; font-size:12px; color:#666; }}
</style>
</head>
<body>
    <div class="header">
        {logo_tag}
        <div class="clinic-info">
            <h1>{esc(CLINIC_NAME)}</h1>
            <div class="meta">{esc(CLINIC_ADDRESS)}<br>Doctor: {esc(CLINIC_DOCTOR)}</div>
            <div class="meta">Report generated: {esc(date_str)}</div>
        </div>
    </div>

    <table>
        <thead>
            <tr><th>ID</th><th>Patient Name</th><th>Doctor</th><th>Date</th></tr>
        </thead>
        <tbody>
            {html_rows}
        </tbody>
    </table>

    <div class="footer">Generated by Dr. N's Dental Studio Management System</div>
</body>
</html>
"""

        try:
            with open(filename, "w", encoding="utf-8") as f:
                f.write(html_content)
        except Exception as e:
            QMessageBox.warning(self, "Export HTML", f"Failed to write HTML file:\n{e}")
            return

        try:
            webbrowser.open(f"file://{os.path.abspath(filename)}")
        except Exception:
            pass

        QMessageBox.information(self, "Export HTML", f"Appointments report exported successfully as:\n{filename}")
